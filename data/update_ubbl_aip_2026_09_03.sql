-- Official UBBL operational data from Azerbaijan AIP AD 2 UBBL.
-- Intentionally does not change TBL_RUNWAYS dimensions/geometries or TBL_RUNWAY_STRIP.
BEGIN;

DO $$
BEGIN
  IF (SELECT count(*) FROM "TBL_AIRPORTS" a JOIN "DIC_ICAO_CODES" i ON i."ICAO_ID"=a."ICAO_ID" WHERE i."ICAO_CODE"='UBBL') <> 1 THEN
    RAISE EXCEPTION 'Expected exactly one UBBL airport';
  END IF;
  IF (SELECT count(*) FROM "TBL_RUNWAY_DIRECTIONS" d JOIN "TBL_RUNWAYS" r ON r."RUN_ID"=d."RUN_ID" JOIN "TBL_AIRPORTS" a ON a."AIR_ID"=r."AIR_ID" JOIN "DIC_ICAO_CODES" i ON i."ICAO_ID"=a."ICAO_ID" WHERE i."ICAO_CODE"='UBBL' AND d."DESIGNATOR" IN ('15','33')) <> 2 THEN
    RAISE EXCEPTION 'Expected UBBL runway directions 15 and 33';
  END IF;
END $$;

UPDATE "TBL_AIRPORTS" a
SET "ELEVATION_M"=-11.000,
    "ARP_GEOM"=ST_SetSRID(ST_MakePoint(48.8063888889,38.7586111111),4326),
    "LAST_EDITED_DATE"=CURRENT_TIMESTAMP
FROM "DIC_ICAO_CODES" i
WHERE i."ICAO_ID"=a."ICAO_ID" AND i."ICAO_CODE"='UBBL';

UPDATE "TBL_RUNWAY_DIRECTIONS" d
SET "TRUE_BEARING_DEG"=CASE d."DESIGNATOR" WHEN '15' THEN 151.0300 ELSE 331.0300 END,
    "THRESHOLD_ELEVATION_M"=CASE d."DESIGNATOR" WHEN '15' THEN -15.850 ELSE -10.668 END,
    "SLOPE_PCT"=CASE d."DESIGNATOR" WHEN '15' THEN 0.1600 ELSE -0.1600 END,
    "THRESHOLD_GEOM"=CASE d."DESIGNATOR"
      WHEN '15' THEN ST_SetSRID(ST_MakePoint(48.7971222222,38.7717194444),4326)
      ELSE ST_SetSRID(ST_MakePoint(48.8155000000,38.7457083333),4326)
    END,
    "LAST_EDITED_DATE"=CURRENT_TIMESTAMP
FROM "TBL_RUNWAYS" r
JOIN "TBL_AIRPORTS" a ON a."AIR_ID"=r."AIR_ID"
JOIN "DIC_ICAO_CODES" i ON i."ICAO_ID"=a."ICAO_ID"
WHERE d."RUN_ID"=r."RUN_ID" AND i."ICAO_CODE"='UBBL' AND d."DESIGNATOR" IN ('15','33');

UPDATE "TBL_RUNWAY_DECLARED_DISTANCES" x
SET "TORA_M"=3300.000,
    "TODA_M"=3600.000,
    "ASDA_M"=3300.000,
    "LDA_M"=3300.000,
    "LAST_EDITED_DATE"=CURRENT_TIMESTAMP
FROM "TBL_RUNWAY_DIRECTIONS" d
JOIN "TBL_RUNWAYS" r ON r."RUN_ID"=d."RUN_ID"
JOIN "TBL_AIRPORTS" a ON a."AIR_ID"=r."AIR_ID"
JOIN "DIC_ICAO_CODES" i ON i."ICAO_ID"=a."ICAO_ID"
WHERE x."RUN_DIR_ID"=d."RUN_DIR_ID" AND i."ICAO_CODE"='UBBL' AND d."DESIGNATOR" IN ('15','33');

COMMIT;
